//! Per-Dname committed tables: 506 Dnames → flash/ram/base exact (PDSC IROM1/IRAM1),
//! each a donor + removal delta over the 33 SVD donor `PERIPHERALS` tables
//! (32 STM32 + `tm4c123gh6pm`; Tiva flash lives at `0x0000_0000` via `flash_base`).
//!
//! Migration note (`ffe651b` → here): the 486 per-variant `stm32*.rs` copies were
//! proven byte-identical to their donor minus `removed` (39,131 shared
//! `PeripheralDef` blocks checked, 0 mismatches, unambiguous donors) and deleted.
//! `core_only_board_per_dname` filters the donor slice at runtime, so simulation
//! behavior is unchanged while `svd/` shrinks from ~1.3G back to the donors.
//!
//! Correction (WP4): F7/G0 Dnames were assigned without ever generating from
//! their own SVDs (the "variant copies" were donor-SVD output). `stm32f746`
//! and `stm32g070` are true own-SVD donors; F7/G0 deltas below are diffed
//! against real silicon layouts.

use super::PeripheralDef;

/// Per-variant chip descriptor (donor plus removal deltas).
pub struct PerDname {
    /// CMSIS device name.
    pub dname: &'static str,
    /// Flash size in bytes.
    pub flash_len: u32,
    /// RAM size in bytes.
    pub ram_len: u32,
    /// Flash base address (`0x0800_0000` STM32, `0x0000_0000` Tiva).
    pub flash_base: u32,
    /// One of the 21 SVD donors below (`donor_peripherals`).
    pub donor: &'static str,
    /// Peripheral names present in the donor but absent on this Dname.
    pub removed: &'static [&'static str],
}

