impl PerDname {
    /// Find a peripheral by SVD name unless this Dname removes it.
    #[must_use]
    pub fn peripheral(&self, name: &str) -> Option<&'static PeripheralDef> {
        if self.removed.contains(&name) {
            return None;
        }
        donor_peripherals(self.donor)
            .iter()
            .find(|p| p.name == name)
    }

    /// Every peripheral this Dname has, in donor file order.
    pub fn peripherals(&self) -> impl Iterator<Item = &'static PeripheralDef> + '_ {
        donor_peripherals(self.donor)
            .iter()
            .filter(|p| !self.removed.contains(&p.name))
    }

    /// Peripheral count after filtering (regression anchor: sum over all
    /// Dnames is 40062).
    #[must_use]
    pub fn len(&self) -> usize {
        self.peripherals().count()
    }

    /// Whether filtering removed every peripheral.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.peripherals().next().is_none()
    }
}

